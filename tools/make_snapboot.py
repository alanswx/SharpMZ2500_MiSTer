#!/usr/bin/env python3
"""Build rtl/mz2500_snapboot.sv, the RAM-image boot stub, from a sim I/O trace of the IPL loading a tape in MZ-2000 mode.

  tools/make_snapboot.py io.csv > rtl/mz2500_snapboot.sv

io.csv is verilator/Vtop --boot-mode 2000 --tape tiny.mzt --type 660:C --trace-io io.csv (frame,addr,port,data: addr is
the full address bus of the OUT, so ports that decode A15-A8, AE and CC, keep their high byte). The IPL's writes up to
its handover (OUT (B7) with bit 1 set, then JP 0000) are replayed by a loop over a table of (C, B, A) triples:

  0000  DI / LD HL,0010h
  0004  LD C,(HL) / INC HL / LD B,(HL) / INC HL / LD A,(HL) / INC HL / OUT (C),A / JR 0004h
  0010  table; the last entry is B7, which maps pages 00-07, and the core resets the CPU into the image

Left out: the MMU (B4/B5: B7 maps 00-07 anyway), the FDC (D8-DB: the IPL's disk boot attempt), PIT latch commands
and PIO port A keyboard scans (only the last E8 value counts). The 8255 (E0-E3) goes last as the mode word and the
final port values: the IPL's own startup pulses PC1 (special reset), which would map the stub away.
"""
import sys

STREAM = {0xA0, 0xA1, 0xA2, 0xA3, 0xE4, 0xE5, 0xE6}   # writes with side effects beyond the register value (SIO, PIT)


def main():
    rows = []
    for line in open(sys.argv[1]).read().split('\n')[1:]:
        if line:
            f, a, p, d = line.split(',')
            rows.append((int(a, 16), int(p, 16), int(d, 16)))
    end = next(i for i, (a, p, d) in enumerate(rows) if p == 0xB7 and d & 2)
    b7 = rows[end][2]
    out, last, pa, pc = [], {}, 0, 0
    for a, p, d in rows[:end]:
        if p in (0xB4, 0xB5, 0xB7) or 0xD8 <= p <= 0xDB:
            continue
        if p == 0xE7 and d & 0x30 == 0:                 # counter latch
            continue
        if p == 0xE0: pa = d; continue
        if p == 0xE2: pc = d; continue
        if p == 0xE3:
            if d & 0x80: pa, pc = 0, 0
            else: pc = (pc & ~(1 << ((d >> 1) & 7))) | ((d & 1) << ((d >> 1) & 7))
            continue
        if p in (0xE1, 0xE8, 0xDC, 0xCE, 0xCF):
            last[p] = (a, d)
            continue
        if out and out[-1] == (a, d) and p not in STREAM:
            continue
        out.append((a, d))
    table = out + [last[p] for p in (0xDC, 0xCE, 0xCF, 0xE8) if p in last]
    assert not pc & 2 and pc & 8, 'PC1 must end low, PC3 (BST) high: %02X' % pc
    table += [(0x00E3, 0x82), (0x00E0, pa), (0x00E2, pc), (0x00B7, b7)]
    code = [0xF3, 0x21, 0x10, 0x00, 0x4E, 0x23, 0x46, 0x23, 0x7E, 0x23, 0xED, 0x79, 0x18, 0xF6, 0x00, 0x00]
    for a, d in table:
        code += [a & 0xFF, a >> 8, d]
    assert len(code) <= 1024, len(code)
    print('// RAM-image boot stub (rtl/mz2500.sv "RAM image boot"): generated by tools/make_snapboot.py from the IPL\'s I/O')
    print('// writes in MZ-2000 mode up to its jump into a loaded tape program; %d writes, then B7 = %02Xh.' % (len(table) - 1, b7))
    print('module mz2500_snapboot')
    print('(')
    print('\tinput            clk,')
    print('\tinput      [9:0] addr,')
    print('\toutput reg [7:0] q')
    print(');')
    print('')
    print('always @(posedge clk)')
    print('\tcase (addr)')
    for i, b in enumerate(code):
        print("\t\t10'h%03X: q <= 8'h%02X;" % (i, b))
    print("\t\tdefault: q <= 8'h00;")
    print('\tendcase')
    print('')
    print('endmodule')
    for a, d in table:
        print('%04X %02X' % (a, d), file=sys.stderr)


if __name__ == '__main__':
    main()
